-- Sayeed Courses — Admin Database Repair / Migration
-- Safe to run on the existing project.
-- It adds only missing admin-phase structures/columns and refreshes the required policies.

begin;

-- =========================================================
-- 1) PUBLIC CATALOGUE: add admin-managed fields if missing
-- =========================================================
alter table public.course_catalogue
  add column if not exists rating numeric(2,1) not null default 4.5,
  add column if not exists review_count bigint not null default 0,
  add column if not exists is_published boolean not null default true,
  add column if not exists updated_at timestamptz not null default now();

-- =========================================================
-- 2) NOTIFICATIONS: add admin-managed fields if missing
-- =========================================================
alter table public.notifications
  add column if not exists is_published boolean not null default true,
  add column if not exists updated_at timestamptz not null default now();

-- =========================================================
-- 3) ADMIN ALLOWLIST
-- =========================================================
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'admin' check (role in ('admin','super_admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- =========================================================
-- 4) COUPONS — this is what the Admin Coupon screen needs
-- =========================================================
create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_percent integer not null check (discount_percent between 1 and 100),
  expires_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists coupons_code_idx on public.coupons (code);

-- =========================================================
-- 5) ADMIN AUDIT LOG
-- =========================================================
create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  admin_user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  entity text not null,
  entity_id bigint,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_log_admin_idx
  on public.admin_audit_log (admin_user_id, created_at desc);

-- =========================================================
-- 6) ENABLE RLS ON ADMIN TABLES
-- =========================================================
alter table public.admin_users enable row level security;
alter table public.coupons enable row level security;
alter table public.admin_audit_log enable row level security;

-- =========================================================
-- 7) PUBLIC READ: only published catalogue + notifications
-- =========================================================
drop policy if exists "public read course catalogue" on public.course_catalogue;
create policy "public read course catalogue"
on public.course_catalogue
for select
to anon
using (is_published = true);

drop policy if exists "public read notifications" on public.notifications;
create policy "public read notifications"
on public.notifications
for select
to anon
using (is_published = true);

-- =========================================================
-- 8) ADMIN TABLES: NO DIRECT BROWSER ACCESS
--    Admin API uses the server-only secret key.
-- =========================================================
revoke select, insert, update, delete on public.admin_users from anon, authenticated;
revoke select, insert, update, delete on public.coupons from anon, authenticated;
revoke select, insert, update, delete on public.admin_audit_log from anon, authenticated;

-- Admin mutations are also blocked for browser roles.
revoke insert, update, delete on public.course_catalogue from anon, authenticated;
revoke insert, update, delete on public.notifications from anon, authenticated;

